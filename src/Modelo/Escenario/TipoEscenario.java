package Modelo.Escenario;

public enum TipoEscenario {
    CARRETA,
    BOSQUE,
    CALABOZO,
    PANTANO
}

/* Un enum (Enumeración) en Java es un tipo de dato especial que se utiliza para definir
 un grupo cerrado de constantes fijas que nunca cambian.

¿Qué hace concretamente este código?
Define los cuatro biomas posibles de tu juego (CARRETA, BOSQUE, CALABOZO, PANTANO) como opciones
 únicas y predefinidas.
Al declararlos dentro del paquete controlador, este archivo funciona
 como una lista oficial de escenarios que todo el sistema puede consultar y usar. */